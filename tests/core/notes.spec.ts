import assert from 'node:assert/strict';
import { cpSync, mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { execFileSync, spawn, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { archiveNote, parseNote, readNote, scanNotes, validateArchive, validateNotes } from '../../skills/write-notes-like-deepseek/scripts/lib/index.ts';

const tmp = mkdtempSync(join(tmpdir(), 'notes-core-'));
try {
  const parser = readFileSync(new URL('../../skills/write-notes-like-deepseek/scripts/lib/parser.mjs', import.meta.url), 'utf8').replace(/export function /g, 'function ');
  const html = readFileSync(new URL('../../skills/write-notes-like-deepseek/assets/agent-notes-board.html', import.meta.url), 'utf8');
  assert.ok(html.includes(parser), 'standalone board must embed the shared parser');
  const root = join(tmp, 'notes');
  const absent = join(tmp, 'absent');
  assert.equal(scanNotes(absent).notes.length, 0);
  assert.equal(validateNotes(absent).issues.length, 0);
  assert.equal(existsSync(absent), false);
  const dir = join(root, 'implemented/process');
  mkdirSync(dir, { recursive: true });
  const note = (title: string, extra = '') => `# Agent Note: ${title}\n\nStatus: implemented\n\n## Problem\nA problem.\n\n## Decision\nA decision.\n\n## Alternatives considered\nAnother choice.\n\n## Consequences\nA result.\n${extra}`;
  const a = 'implemented/process/2026-10-01-a.md';
  const b = 'implemented/process/2026-10-01-b.md';
  writeFileSync(join(root, a), note('A', '\n[B](2026-10-01-b.md#part)\n'));
  writeFileSync(join(root, b), note('B'));
  const zh = 'implemented/process/2026-10-01-b.zh.md';
  writeFileSync(join(root, zh), note('B 中文'));
  const parsed = scanNotes(root).notes;
  assert.equal(parsed.find((x: any) => x.id === zh)?.title, 'B 中文');
  assert.match(readNote(root, zh), /B 中文/);
  assert.deepEqual(parsed.find((x: any) => x.id === a).outLinks, [b]);
  const duplicateId = 'proposed/process/2026-10-01-b.md';
  const unresolved = parseNote('[bad](../testing/2026-10-01-b.md)', a, new Set([b, duplicateId]));
  assert.deepEqual(unresolved.outLinks, []);
  assert.equal(parsed.find((x: any) => x.id === a).decision, 'A decision.');
  const fake = parseNote('```\n## Problem\nwrong\n```\n## Problem\nright\n', a, new Set());
  assert.equal(fake.problem, 'right');
  const outside = join(tmp, 'secret.md');
  writeFileSync(outside, 'secret');
  symlinkSync(outside, join(dir, '2026-10-01-secret.md'));
  assert.throws(() => readNote(root, 'implemented/process/2026-10-01-secret.md'), /symlink/);
  assert.equal(scanNotes(root).notes.some((x: any) => x.rawBody === 'secret'), false);
  assert.throws(() => readNote(root, '../secret.md'), /escapes/);
  assert.equal(validateNotes(root).issues.length, 0);
  const formatCli = fileURLToPath(new URL('../../skills/write-notes-like-deepseek/scripts/verify-agent-note-format.ts', import.meta.url));
  const cli = () => spawnSync('npx', ['-y', 'tsx', formatCli, '--root', root], { cwd: tmp, encoding: 'utf8' });
  assert.equal(cli().status, 0);
  writeFileSync(join(root, a), note('A').replace('Status: implemented', 'Status: proposed'));
  assert.equal(cli().status, 1);
  writeFileSync(join(root, a), note('A', '\n[B](2026-10-01-b.md#part)\n'));
  const results = await Promise.all([archiveNote(root, a), archiveNote(root, b)]);
  assert.ok(results.every(result => result.ok), JSON.stringify(results));
  const manifest = JSON.parse(readFileSync(join(root, 'archived/manifest.json'), 'utf8'));
  assert.equal(Object.keys(manifest.files).length, 2);
  assert.equal(validateNotes(root).issues.length, 0);
  const c = 'implemented/process/2026-10-01-c.md';
  const d = 'implemented/process/2026-10-01-d.md';
  writeFileSync(join(root, c), note('C'));
  writeFileSync(join(root, d), note('D'));
  writeFileSync(join(root, 'archived/process/2026-10-01-old.md'), note('Old').replace('Status: implemented\n', 'Status: implemented\nArchived: 2026-10-01\n'));
  writeFileSync(join(root, 'archived/.seal.lock'), '99999999:0:dead');
  const archiveCli = fileURLToPath(new URL('../../skills/write-notes-like-deepseek/scripts/archive-agent-note.ts', import.meta.url));
  const runArchive = (id: string) => new Promise<void>((resolve, reject) => {
    const child = spawn('npx', ['-y', 'tsx', archiveCli, join(root, id), '--root', root], { cwd: tmp, stdio: 'pipe' });
    let output = '';
    child.stdout.on('data', chunk => output += chunk);
    child.stderr.on('data', chunk => output += chunk);
    child.on('error', reject);
    child.on('close', code => code === 0 ? resolve() : reject(new Error(`archive exit ${code}: ${output}`)));
  });
  const sealCli = fileURLToPath(new URL('../../skills/write-notes-like-deepseek/scripts/verify-archived-agent-notes.ts', import.meta.url));
  const seal = new Promise<void>((resolve, reject) => {
    const child = spawn('npx', ['-y', 'tsx', sealCli, '--write', '--root', root], { cwd: tmp, stdio: 'pipe' });
    let output = '';
    child.stdout.on('data', chunk => output += chunk);
    child.stderr.on('data', chunk => output += chunk);
    child.on('error', reject);
    child.on('close', code => code === 0 ? resolve() : reject(new Error(`seal exit ${code}: ${output}`)));
  });
  await Promise.all([runArchive(c), runArchive(d), seal]);
  const afterConcurrent = JSON.parse(readFileSync(join(root, 'archived/manifest.json'), 'utf8'));
  assert.equal(Object.keys(afterConcurrent.files).length, 5);
  Object.assign(manifest.files, afterConcurrent.files);
  assert.equal(validateNotes(root).issues.length, 0);
  const git = (args: string[]) => execFileSync('git', args, { cwd: root, stdio: 'ignore', env: { ...process.env, GIT_AUTHOR_NAME: 'Test', GIT_AUTHOR_EMAIL: 'test@example.com', GIT_COMMITTER_NAME: 'Test', GIT_COMMITTER_EMAIL: 'test@example.com' } });
  git(['init']);
  git(['add', '.']);
  git(['commit', '-m', 'baseline']);
  delete manifest.files['archived/process/2026-10-01-a.md'];
  writeFileSync(join(root, 'archived/manifest.json'), JSON.stringify(manifest));
  const baselineIssues = validateNotes(root).issues;
  assert.ok(baselineIssues.some(issue => issue.rule === 'archived.seal-baseline'));
  const mirror = join(tmp, 'mirror');
  mkdirSync(mirror);
  cpSync(join(root, 'archived'), join(mirror, 'archived'), { recursive: true });
  const baselineRaw = JSON.stringify(afterConcurrent);
  const supplied = validateNotes(mirror, { archiveBaseline: { raw: baselineRaw, ref: 'captured-commit', warnings: ['captured warning'] } });
  assert.ok(supplied.issues.some(issue => issue.rule === 'archived.seal-baseline' && issue.message.includes('captured-commit')));
  assert.deepEqual(supplied.warnings, ['captured warning']);
  const noBaseline = validateArchive(root, { archiveBaseline: { raw: null, ref: 'no-manifest' } });
  assert.equal(noBaseline.errors.some(error => error.includes('append-only')), false, 'explicit null must suppress local git lookup');
  assert.deepEqual(noBaseline.warnings, []);
  const badBaseline = validateArchive(mirror, { archiveBaseline: { raw: '{', ref: 'bad-ref' } });
  assert.ok(badBaseline.errors.some(error => error.includes('at bad-ref was not valid JSON')));
  const goodBaseline = validateArchive(mirror, { archiveBaseline: { raw: JSON.stringify(manifest), ref: 'matching' } });
  assert.equal(goodBaseline.errors.some(error => error.includes('append-only')), false);
  assert.deepEqual(goodBaseline.warnings, []);
  assert.equal(JSON.parse(readFileSync(join(root, 'archived/manifest.json'), 'utf8')).files['archived/process/2026-10-01-a.md'], undefined);
  console.log('ok: isolated roots, parser, symlink boundary, read-only checks, concurrent archive and git baseline');
} finally { rmSync(tmp, { recursive: true, force: true }); }
